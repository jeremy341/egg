/**
 * Regenerate the Markdown views of the docs from the same TSX the site renders.
 *
 * Run with: pnpm docs:generate
 *
 * This runs outside Next's compiler, where "use client" is just a string, so
 * react-dom/server can render the whole page including its small interactive
 * islands. The generated module is checked in; the App Router routes serve it
 * without importing react-dom/server (which Next forbids in route handlers).
 */
import { createElement, Fragment } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { CONTENT } from "../src/app/(docs)/docs/_content";
import { htmlToMarkdown } from "../src/app/(docs)/docs/_data/markdown-render";
import { DOCS_NAV, DOCS_SECTIONS } from "../src/app/(docs)/docs/_data/nav";
import { SUMMARIES } from "../src/app/(docs)/docs/_data/summaries";

function pageMarkdown(id: string): string {
  const render = CONTENT[id];
  if (!render) throw new Error(`No docs content for ${id}`);
  const html = renderToStaticMarkup(createElement(Fragment, null, render()));
  return `${htmlToMarkdown(html)}\n`;
}

const pages: Record<string, string> = {};
for (const section of DOCS_SECTIONS) pages[section.id] = pageMarkdown(section.id);

const full = `# Egg docs\n\n${DOCS_SECTIONS.map((s) => pages[s.id]).join("\n\n---\n\n")}\n`;

const indexLines = ["# Egg docs", "", "> Egg pushes a GitHub repository to a free Hack Club Nest container. These are its docs.", ""];
for (const { group, sections } of DOCS_NAV) {
  indexLines.push(`## ${group}`, "");
  for (const s of sections) indexLines.push(`- [${s.title}](__EGG_ORIGIN__/docs/${s.id}.md): ${SUMMARIES[s.id] ?? ""}`.trimEnd());
  indexLines.push("");
}

const out = `// Generated by scripts/generate-docs-markdown.ts. Do not edit by hand.\nexport const PAGES: Record<string, string> = ${JSON.stringify(pages)};\nexport const FULL = ${JSON.stringify(full)};\nexport const INDEX = ${JSON.stringify(indexLines.join("\n"))};\n`;
const target = path.join(process.cwd(), "src/app/(docs)/docs/_data/generated-markdown.ts");
writeFileSync(target, out, "utf8");
console.log(`Wrote ${target} (${DOCS_SECTIONS.length} pages, ${out.length} chars)`);
