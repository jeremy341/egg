import { afterAll, beforeAll, expect, it, vi } from "vitest";
import { NextRequest } from "next/server";
import { eq } from "drizzle-orm";
import { schema } from "@/server/db";
import { upsertUser } from "@/server/auth/session";
import { useFreshDb } from "@/server/test/db";
vi.mock("@/server/auth/current", () => ({ getCurrentUser: vi.fn(), requireUser: vi.fn() }));
import { getCurrentUser } from "@/server/auth/current";
import { POST as invite } from "@/app/api/projects/[id]/invitations/route";
import { POST as accept } from "@/app/api/project-invitations/accept/route";
let ctx: Awaited<ReturnType<typeof useFreshDb>>;
let owner: Awaited<ReturnType<typeof upsertUser>>, recipient: typeof owner, other: typeof owner;
const req = (url: string, body: unknown) => new NextRequest(url, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
beforeAll(async () => {
  ctx = await useFreshDb();
  owner = await upsertUser({ id: "http-owner", name: "Owner", email: null, slackId: null });
  recipient = await upsertUser({ id: "http-recipient", name: "Recipient", email: "person@example.com", slackId: null });
  other = await upsertUser({ id: "http-other", name: "Other", email: "other@example.com", slackId: null });
  await ctx.db.insert(schema.servers).values({ id: "http-s", userId: owner.id, nestUsername: "owner", host: "host", publicKey: "key", privateKeyEnc: "sealed", keyFingerprint: "fp", createdAt: new Date() });
  await ctx.db.insert(schema.projects).values({ id: "http-p", userId: owner.id, serverId: "http-s", slug: "p", name: "P", repoUrl: "https://github.com/a/b", runtime: "node", port: 3000, createdAt: new Date(), updatedAt: new Date() });
});
afterAll(async () => ctx.cleanup());
it("enforces recipient identity through the HTTP routes", async () => {
  vi.mocked(getCurrentUser).mockResolvedValue(owner);
  const create = (body: unknown) => invite(req("http://localhost:3000/api/projects/http-p/invitations", body), { params: Promise.resolve({ id: "http-p" }) });
  expect((await create({ email: "person@example.com", userId: recipient.id, role: "viewer" })).status).toBe(400);
  const emailResponse = await create({ email: "person@example.com", role: "viewer" });
  expect(emailResponse.status).toBe(201);
  const emailToken = (await emailResponse.json()).token;
  const claim = (token: string) => accept(req("http://localhost:3000/api/project-invitations/accept", { token }), undefined);
  vi.mocked(getCurrentUser).mockResolvedValue(recipient);
  expect((await claim(emailToken)).status).toBe(404);
  await ctx.db.update(schema.users).set({ emailVerified: true }).where(eq(schema.users.id, recipient.id));
  expect((await claim(emailToken)).status).toBe(200);
  expect((await claim(emailToken)).status).toBe(404);
  vi.mocked(getCurrentUser).mockResolvedValue(owner);
  const direct = await create({ userId: other.id, role: "developer" });
  expect(direct.status).toBe(201);
  const token = (await direct.json()).token;
  vi.mocked(getCurrentUser).mockResolvedValue(recipient);
  expect((await claim(token)).status).toBe(404);
  vi.mocked(getCurrentUser).mockResolvedValue(other);
  expect((await claim(token)).status).toBe(200);
});
